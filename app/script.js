let audioMuted = reduceMotion;
function clickBeep() {
  if (audioMuted) return;
  try {
    audioCtx = audioCtx || new (window.AudioContext || window.webkitAudioContext)();
    const o = audioCtx.createOscillator();
    const g = audioCtx.createGain();
    o.type = "square";
    o.frequency.value = 880;
    g.gain.value = 0.03;
    o.connect(g).connect(audioCtx.destination);
    o.start();
    o.frequency.exponentialRampToValueAtTime(220, audioCtx.currentTime + 0.08);
    g.gain.exponentialRampToValueAtTime(0.0001, audioCtx.currentTime + 0.1);
    o.stop(audioCtx.currentTime + 0.11);
  } catch (e) {}
}
/* One delegated listener instead of one per element. */
document.addEventListener("click", (e) => {
  if (e.target.closest("a, button")) clickBeep();
});
