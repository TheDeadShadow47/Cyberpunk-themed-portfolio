const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

let lang = localStorage.getItem("portfolio.lang") || "EN";

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const entry = dict[key];
    if (!entry) return;
    const value = entry[lang] ?? entry.EN;
    el.textContent = value;
    if (el.hasAttribute("data-text")) el.setAttribute("data-text", value);
  });
  document.documentElement.lang = lang === "AR" ? "ar" : "en";
  document.documentElement.dir  = lang === "AR" ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", lang === "AR");

  const cur = document.getElementById("lang-current");
  const oth = document.getElementById("lang-other");
  if (cur) cur.textContent = lang;
  if (oth) oth.textContent = lang === "EN" ? "AR" : "EN";
  const f = document.getElementById("footer-lang");
  if (f) f.textContent = lang;
}

const langBtn = document.getElementById("lang-toggle");
if (langBtn) {
  langBtn.addEventListener("click", () => {
    if (reduceMotion) {
      lang = lang === "EN" ? "AR" : "EN";
      localStorage.setItem("portfolio.lang", lang);
      applyI18n();
      return;
    }
    document.body.classList.add("glitching");
    setTimeout(() => {
      lang = lang === "EN" ? "AR" : "EN";
      localStorage.setItem("portfolio.lang", lang);
      applyI18n();
    }, 220);
    setTimeout(() => document.body.classList.remove("glitching"), 600);
  });
}

applyI18n();

